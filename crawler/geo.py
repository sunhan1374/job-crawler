def _dist_km(a, b):
    lat1, lon1 = a
    lat2, lon2 = b
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def lookup(location: str):
    """'서울 강남구' / '경기 용인시 기흥구 외' → (대표역, 집까지 거리km).

    못 찾으면 (None, None).
    """
    loc = location or ""
    for key, station, lat, lon in PLACES:
        if key in loc:
            return station, round(_dist_km(HOME, (lat, lon)), 1)
    return None, None
